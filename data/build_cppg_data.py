def build_cppg_cert():
    subjects_data = []
    
    for s_def in SUBJECT_DEFS:
        s_no = s_def["subject_no"]
        s_code = s_def["code"]
        s_name = s_def["name"]
        s_desc = s_def["description"]
        cats_raw = s_def["categories"]
        
        subcats_data = []
        for cat_idx, (cat_title, topics_raw) in enumerate(cats_raw, start=1):
            cat_id = f"{s_code}_CAT_{cat_idx:02d}"
            
            topics_data = []
            for top_idx, (t_title, t_prob, t_core, t_prac, t_terms) in enumerate(topics_raw, start=1):
                top_id = f"{s_code}_{cat_idx:02d}_{top_idx:02d}"
                
                # YouTube/강의 요약 생성
                terms_str = ", ".join(t_terms[:3])
                summary_text = (
                    f"💡 [{t_title}]\n"
                    f"1. CPPG 시험은 조문 문구의 '하여야 한다(의무)'와 '할 수 있다(재량)' 구분이 합격의 당락을 가릅니다.\n"
                    f"2. 최근 개정 개인정보보호법 및 표준 개인정보 보호지침의 최신 판례·과징금 기준을 철저히 암기하세요.\n"
                    f"- 핵심 시험 연계 키워드: {terms_str}"
                )
                
                yt_channel = "CPPG 단기완성 (개인정보보호 실무특강)" if top_idx % 2 == 1 else "CPO 포럼 개인정보 핵심정리"
                
                topic_item = {
                    "title": t_title,
                    "prob": t_prob,
                    "core": t_core,
                    "prac": t_prac,
                    "id": top_id,
                    "frequency": f"출제 확률 {t_prob} (CPPG 필기/실기 빈출)",
                    "probability": t_prob,
                    "core_concepts": t_core,
                    "practical_point": t_prac,
                    "related_terms": t_terms,
                    "youtube_tips": {
                        "channel": yt_channel,
                        "mnemonic": "",
                        "lecture_summary": summary_text
                    }
                }
                topics_data.append(topic_item)
                
            subcats_data.append({
                "cat_id": cat_id,
                "cat_name": cat_title,
                "topics": topics_data
            })
            
        subjects_data.append({
            "subject_no": s_no,
            "code": s_code,
            "name": s_name,
            "description": s_desc,
            "subcategories": subcats_data
        })
        
    return {
        "id": CPP_CERT_META["id"],
        "title": CPP_CERT_META["title"],
        "subtitle": CPP_CERT_META["subtitle"],
        "badge": CPP_CERT_META["badge"],
        "description": CPP_CERT_META["description"],
        "passing_criteria": CPP_CERT_META["passing_criteria"],
        "subjects": subjects_data
    }

